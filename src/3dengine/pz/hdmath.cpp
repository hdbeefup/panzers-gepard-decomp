// src/3dengine/pz/hdmath.cpp
// The HD CRT maths routines the game logic and the engine share (see
// hdmath.h). Moved here from src/game/drivermath.cpp (agent P's port) so
// the engine (SModel node transforms) uses the same code as the drivers.
//
// HdSin/HdCos/HdTan are transcriptions of the SSE2 code of the CRT routines
// in PANZERS.exe (__libm_sse2_sin/cos/tan, VS2005 CRT): every SSE2
// instruction of the main path maps to one intrinsic on the same register
// (x0..x7 = xmm0..xmm7), so the result is bit-identical (SSE2 double ops are
// exact IEEE operations). The constant tables are copied byte for byte from
// the exe (0x8a38b0..0x8a3a90, 0x8a8140..0x8a9f60). The main-path blocks
// were generated from the disassembly (one comment per HD instruction).
// Verified against the HD functions run in the unicorn emulator (millions of
// inputs, bit for bit) and natively against the HD code bytes.
//
// The x87 parts (atan2, the out-of-range fallback of sin/cos/tan) use MSVC
// x86 inline asm so that the x87 rounding (precision control) is exactly the
// HD one. They need x86 (the project is x86-only).

